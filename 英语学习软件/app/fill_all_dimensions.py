    if not words_in_coll: continue

    # 找到第一个实义词对应的sense_id
    sense_id = None
    for w in words_in_coll:
        if w in all_words:
            wid = all_words[w]
            cur.execute("SELECT id FROM word_senses WHERE word_id = ? LIMIT 1", (wid,))
            row = cur.fetchone()
            if row:
                sense_id = row[0]
                break
    if sense_id is None: continue
    if sense_id in existing_coll: continue

    coll_rows.append((coll_id, sense_id, collocation, coll_type, example, example_cn, None))
    existing_coll.add(sense_id)
    coll_id += 1

