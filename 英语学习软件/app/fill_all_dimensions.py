def insert_many(table, cols, rows, batch_size=50):
    """批量插入，返回插入数"""
    total = 0
    for i in range(0, len(rows), batch_size):
        batch = rows[i:i+batch_size]
        vals = ','.join(f"({','.join(repr(v) for v in r)})" for r in batch)
        sql = f"INSERT OR IGNORE INTO {table} ({','.join(cols)}) VALUES {vals}"
        try:
            cur.execute(sql)
            conn.commit()
            total += cur.rowcount
        except Exception as e:
            print(f"  ERROR {table}: {e}")
    return total

